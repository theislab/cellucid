#!/usr/bin/env node
/**
 * Write the keyboard shortcuts page of the docs from the one shortcut table
 * (`assets/js/app/ui/onboarding/shortcut-table.js`): the same groups and rows
 * the Keyboard shortcuts panel draws, and for each camera key the navigation
 * modes that answer it (`rendering/navigation-keys.js`).
 *
 *   node scripts/generate-shortcut-reference.mjs           # write it
 *   node scripts/generate-shortcut-reference.mjs --check   # exit 1 when it is stale or missing
 *   node scripts/generate-shortcut-reference.mjs --out <file>
 *
 * The page lives in the shared docs site (`cellucid-python/docs`, found
 * through CELLUCID_PYTHON_DOCS, else the sibling checkout):
 * `user_guide/web_app/o_accessibility_privacy_security/03_keyboard_shortcuts.md`.
 * `tests/keyboard-shortcut-table-contract.test.mjs` fails while it differs
 * from what this writes, so a key added to the table cannot leave the docs
 * behind.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { pythonDocsRoot } from './shared-files.mjs';
import { SHORTCUT_GROUPS } from '../assets/js/app/ui/onboarding/shortcut-table.js';
import { NAVIGATION_KEY_MODES } from '../assets/js/rendering/navigation-keys.js';

/** Where the page is, inside the docs tree. */
export const SHORTCUT_REFERENCE_PAGE = path.join(
  'user_guide', 'web_app', 'o_accessibility_privacy_security', '03_keyboard_shortcuts.md',
);

/** The page's path for `env`. */
export function shortcutReferencePath(env = process.env) {
  return path.join(pythonDocsRoot(env), SHORTCUT_REFERENCE_PAGE);
}

const MODE_WORDS = Object.freeze({ orbit: 'Orbit', planar: 'Planar', free: 'Free-fly' });

/** What each group's keys act on, said once under its heading. */
const GROUP_WORDS = Object.freeze({
  general: 'Anywhere on the page, unless focus is in a text field, a list or a dialog (which keep the keys typed in them).',
  navigation: 'The camera of the focused view (linked views follow it). Held keys move it for as long as they are held.',
  zoom: 'The camera of the focused view.',
  'free-fly': 'The camera in Free-fly.',
  selection: 'On the plot, with a selection tool chosen.',
  history: 'A focused row of the History list (State panel); the History (i) lists them too.',
  move: 'One way to move a thing to a place by keys, wherever it can be dragged: a panel floated or docked, a highlight page into Create categorical and its order, a legend category onto another to merge them. Each place is announced as it is chosen.',
});

/** Text safe in a Markdown table cell (and in MyST): no pipes, no tags, one line. */
function cell(text) {
  return String(text).replaceAll('|', '\\|').replaceAll('<', '&lt;').replaceAll('\n', ' ');
}

/** A combo as MyST keys: {kbd}`Shift+Alt`+click. */
function comboText(combo) {
  const keys = `{kbd}\`${combo.keys.join('+').replaceAll('`', '')}\``;
  return combo.gesture === undefined ? keys : `${keys}+${combo.gesture}`;
}

/** The modes a row of camera keys acts in, or null for a row of other keys. */
function modesOf(row) {
  if (row.movements === undefined && row.modes === undefined) return null;
  const modes = row.modes ?? [...new Set(row.movements.flatMap(movement => NAVIGATION_KEY_MODES[movement]))];
  return ['orbit', 'planar', 'free'].filter(mode => modes.includes(mode)).map(mode => MODE_WORDS[mode]).join(', ');
}

/** The page, from the table. */
export function renderShortcutReference() {
  const missing = SHORTCUT_GROUPS.filter(group => typeof GROUP_WORDS[group.id] !== 'string').map(group => group.id);
  if (missing.length > 0) {
    throw new Error(`The shortcut reference has no words for the group(s) ${missing.join(', ')}; add them to scripts/generate-shortcut-reference.mjs`);
  }
  const lines = [
    '<!-- Generated by cellucid/scripts/generate-shortcut-reference.mjs from the shortcut table',
    '     (cellucid/assets/js/app/ui/onboarding/shortcut-table.js). Do not edit by hand. -->',
    '',
    '# Keyboard shortcuts',
    '',
    'Every key Cellucid answers, as the in-app **Keyboard shortcuts** panel lists them (press {kbd}`?`).',
    'The panel, the keys and this page come from one table, so none of them can list a key the others do not.',
    '',
    'A key is the page\'s unless what has focus uses it itself: a text field types it, a dropdown jumps to',
    'the option a typed letter starts, and a menu, a list or a dialog keeps the keys pressed in it. After',
    'a slider, a checkbox or a button the keys work at once (a slider keeps only its arrows, Home, End and',
    'Page keys; a checkbox Space; a button Enter and Space). A shortcut held down acts once; a camera key',
    'moves the camera for as long as it is held. On a Mac, {kbd}`⌘` stands for {kbd}`Ctrl`.',
    '',
  ];
  for (const group of SHORTCUT_GROUPS) {
    const camera = group.rows.some(row => row.movements !== undefined);
    lines.push(`## ${group.title}`, '', GROUP_WORDS[group.id], '');
    lines.push(camera ? '| Keys | What it does | Modes |' : '| Keys | What it does |');
    lines.push(camera ? '|---|---|---|' : '|---|---|');
    for (const row of group.rows) {
      const spaced = row.combos.some(combo => combo.keys.length > 1 || combo.gesture !== undefined);
      const keys = row.combos.map(comboText).join(spaced ? ' / ' : ' ');
      // The panel shows the title on hover; here it follows as its own sentence.
      const words = row.title === undefined ? row.label : `${row.label}. ${row.title}.`;
      lines.push(camera
        ? `| ${keys} | ${cell(words)} | ${cell(modesOf(row) ?? 'All')} |`
        : `| ${keys} | ${cell(words)} |`);
    }
    lines.push('');
  }
  while (lines.at(-1) === '') lines.pop();
  return `${lines.join('\n')}\n`;
}

async function main(argv) {
  const check = argv.includes('--check');
  const outIndex = argv.indexOf('--out');
  const target = outIndex >= 0 ? path.resolve(argv[outIndex + 1] ?? '') : shortcutReferencePath();
  const text = renderShortcutReference();
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => null);
    if (current !== text) {
      console.error(`${target} is ${current === null ? 'missing' : 'stale'}: run node scripts/generate-shortcut-reference.mjs`);
      process.exitCode = 1;
      return;
    }
    console.log(`${target} is current.`);
    return;
  }
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, text);
  console.log(`Wrote ${target}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main(process.argv.slice(2));
}
